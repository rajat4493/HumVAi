// Writes docs/design/campaign.md from the campaign table and the solver, so the document cannot drift from the game.
//   npx tsx tools/gen-campaign-doc.ts
import { writeFileSync } from 'node:fs';
import { CAMPAIGN, levelById, solve } from '@hva/game-core';

const rows: string[] = [];
let n = 0;
for (const ch of CAMPAIGN) {
  rows.push(`\n## ${ch.name}\n\n${ch.blurb}\n\n| # | World | What it teaches | Optimal | Scout / Run |\n|---|---|---|---|---|`);
  for (const e of ch.levels) {
    n += 1;
    const l = levelById(e.levelId)!;
    const r = solve(l, { maxStates: 2_000_000 });
    rows.push(`| ${n} | ${l.name} (\`${l.id}\`) | ${l.learning} | ${r.optimalLength} | ${l.budget.explore} / ${l.budget.execute} |`);
  }
}
writeFileSync(
  'docs/design/campaign.md',
  `# The 20-world campaign\n\n_Generated by \`tools/gen-campaign-doc.ts\`. Every world passes the solver gates (solvable within budget, no dead states, replay-verified); see \`docs/verification/\`. Spoiler-free briefings and the three hint tiers live in \`packages/game-core/src/campaign.ts\`._\n${rows.join('\n')}\n`,
);
console.log(`wrote ${n} worlds`);

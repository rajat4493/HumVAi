// Regenerates apps/web/src/games/dont-press-that/solutions.ts: one verified winning input list per level (and per beam mode).
// Run after changing a level:  npx tsx tools/dpt-solve.ts
import { writeFileSync } from 'node:fs';
import { LEVELS } from '../apps/web/src/games/dont-press-that/levels';
import { solve } from '../apps/web/src/games/dont-press-that/solver';
import { replay } from '../apps/web/src/games/dont-press-that/sim';

const rle = (inputs: number[]): number[] => {
  const out: number[] = [];
  let i = 0;
  while (i < inputs.length) {
    let j = i;
    while (j < inputs.length && inputs[j] === inputs[i]) j++;
    out.push(inputs[i]! + 16 * (j - i));
    i = j;
  }
  return out;
};

const rows: string[] = [];
for (const level of LEVELS) {
  for (const mode of level.beams === 'adaptive' ? (['lead', 'camp'] as const) : (['lead'] as const)) {
    const r = solve(level, mode, level.id.startsWith('l5') ? { walkOnly: true, weight: 1, maxNodes: 3_000_000 } : { maxNodes: 800_000 });
    if (!r.solved) throw new Error(`${level.id} [${mode}] has no solution`);
    const check = replay(level, r.inputs, mode);
    if (!check.won) throw new Error(`${level.id} [${mode}] solution does not replay`);
    console.log(`${level.id} [${mode}] ${r.ticks} ticks, ${r.nodes} nodes`);
    rows.push(`  { level: '${level.id}', version: ${level.version}, mode: '${mode}', runs: ${JSON.stringify(rle(r.inputs))} },`);
  }
}
writeFileSync(
  'apps/web/src/games/dont-press-that/solutions.ts',
  `// Generated by tools/dpt-solve.ts: do not edit. One winning input list per level (and beam mode), found by search and replayed from a\n// clean start. Used by tests and by the browser tests that play the real game; the game itself never imports this file.\n// Each run is keys + 16 * ticks (keys: 1 left, 2 right, 4 jump).\nexport interface Solution {\n  level: string;\n  version: number;\n  mode: 'lead' | 'camp';\n  runs: number[];\n}\n\nexport const SOLUTIONS: readonly Solution[] = [\n${rows.join('\n')}\n];\n\nexport const expand = (runs: readonly number[]): number[] => runs.flatMap((r) => Array.from({ length: r >> 4 }, () => r & 15));\n`,
);
console.log('written');
